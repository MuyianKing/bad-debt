function normalizeMerchant(merchant) {
  return String(merchant || '').trim().replace(/\s+/g, '').toLowerCase()
}

function loadLearned() {
  try {
    const raw = uni.getStorageSync(STORAGE_KEY)
    if (raw) {
      const map = typeof raw === 'string' ? JSON.parse(raw) : raw
      if (map && typeof map === 'object') return map
    }
  } catch (e) {
    // ignore
  }
  return {}
}

/**
 * 分类建议：用户历史修正 > 内置词典；未命中返回空串（页面回落默认）
 * @param {string} merchant 商户名（草稿 merchant 字段）
 * @param {boolean} isIncome 收支方向
 * @returns {string} 分类叶子名或空串
 */
export function suggestCategory(merchant, isIncome) {
  const norm = normalizeMerchant(merchant)
  if (!norm) return ''
  const learned = loadLearned()
  if (learned[norm]) return learned[norm]
  const dict = isIncome ? DICT_INCOME : DICT_EXPENSE
  for (const pair of dict) {
    if (norm.indexOf(pair[0]) >= 0) return pair[1]
  }
  return ''
}

/**
 * 用户修正回流：确认草稿时记录"商户 → 实际选择的分类"
 * 超过上限后淘汰最早的记录
 */
export function learnCategory(merchant, leafName) {
  const norm = normalizeMerchant(merchant)
  if (!norm || !leafName) return
  const map = loadLearned()
  const keys = Object.keys(map)
  if (!(norm in map) && keys.length >= MAX_LEARNED) {
    delete map[keys[0]]
  }
  map[norm] = leafName
  try {
    uni.setStorageSync(STORAGE_KEY, JSON.stringify(map))
  } catch (e) {
    // ignore
  }
}
